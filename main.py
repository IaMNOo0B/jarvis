# -----------------------------------------------------------------
# Global resources - shared thread pool and simple memoization cache
# -----------------------------------------------------------------
_GLOBAL_EXECUTOR = ThreadPoolExecutor(max_workers=max(4, (os.cpu_count() or 4) * 2))


@functools.lru_cache(maxsize=128)
def _cached_parallel_multi_search(queries: tuple) -> str:
    return actions.parallel_multi_search(list(queries), max_results_per_query=2)


@functools.lru_cache(maxsize=128)
def _cached_parallel_multi_browse(urls: tuple) -> str:
    return actions.parallel_multi_browse(list(urls))



def _script_stub(language: str, description: str) -> str:
    return _generate_script_stub(language, description)


def _generate_script_stub(language: str, description: str) -> str:
    """Minimal production-shaped stub for the requested language."""
    header = f"#!/usr/bin/env {language}\n" if language in ("python", "py") else ""
    return (f"{header}# {description.strip().capitalize()}\n"
            f"# Generated by JARVIS\n\n"
            f"def main():\n    # TODO: implement {description.strip()}\n    pass\n\n\n"
            f"if __name__ == \"__main__\":\n    main()\n")


# -----------------------------------------------------------------
# Helper: simple keyword extraction for auto-research
# -----------------------------------------------------------------
def _extract_keywords(text: str) -> list:
    stopwords = {"the", "and", "or", "a", "an", "of", "to", "in", "for",
                 "with", "on", "by", "as", "is", "are"}
    tokens = re.split(r"[\s,.;:!?]+", text.lower())
    keywords = [t for t in tokens if t and t not in stopwords]
    seen, uniq = set(), []
    for kw in keywords:
        if kw not in seen:
            seen.add(kw)
            uniq.append(kw)
    return uniq[:8]


# -----------------------------------------------------------------
# Auto-Research - parallel multi-search + optional browsing of top URLs
# -----------------------------------------------------------------
def auto_research(user_input: str) -> str:
    keywords = _extract_keywords(user_input)
    if not keywords:
        return ""
    queries = tuple(f"{user_input} {kw}" for kw in keywords)
    future_search = _GLOBAL_EXECUTOR.submit(_cached_parallel_multi_search, queries)
    search_result = future_search.result()

    urls = [m.group(0) for m in re.finditer(r"https?://[^\s]+", search_result)][:4]
    browse_result = ""
    if urls:
        future_browse = _GLOBAL_EXECUTOR.submit(
            _cached_parallel_multi_browse, tuple(urls))
        browse_result = future_browse.result()

    combined = "[Auto-Research Summary]\n" + search_result
    if browse_result:
        combined += "\n\n[Auto-Browse Summary]\n" + browse_result
    return combined


# -----------------------------------------------------------------
# Script-Generation Helpers
# -----------------------------------------------------------------
def _detect_script_requests(user_input: str) -> list:
    patterns = [
        (r"write a (python|py|javascript|js|node|rust|go|golang|c\+\+|cpp|c) script that (.+)", 1, 2),
        (r"create a (python|py|javascript|js|node|rust|go|golang|c\+\+|cpp|c) program that (.+)", 1, 2),
        (r"generate (?:a )?(python|py|javascript|js|node|rust|go|golang|c\+\+|cpp|c) file (.+)", 1, 2),
    ]
    requests = []
    for pat, lang_grp, desc_grp in patterns:
        for match in re.finditer(pat, user_input, flags=re.IGNORECASE):
            requests.append((match.group(lang_grp).lower(),
                             match.group(desc_grp).strip().rstrip('.')))
    return requests


def _file_extension(lang: str) -> str:
    lang = lang.lower()
    return {
        "python": "py", "py": "py", "javascript": "js", "js": "js",
        "node": "js", "c": "c", "c++": "cpp", "cpp": "cpp", "cxx": "cpp",
        "rust": "rs", "go": "go", "golang": "go", "java": "java",
    }.get(lang, "txt")


def auto_generate_and_write_scripts(user_input: str) -> str:
    script_requests = _detect_script_requests(user_input)
    if not script_requests:
        return ""
    results = []

    def _write_one(idx, language, description):
        stub = _script_stub(language, description)
        safe_lang = language.replace('+', 'p').replace('#', 'sharp')
        filename = f"generated_{idx}_{safe_lang}_script.{_file_extension(language)}"
        write_res = actions.write_workspace_file(filename, stub)
        return f"- {filename}: {write_res}"

    with ThreadPoolExecutor(max_workers=max(1, len(script_requests))) as exe:
        futures = [exe.submit(_write_one, i, lang, desc)
                   for i, (lang, desc) in enumerate(script_requests, 1)]
        for f in as_completed(futures):
            results.append(f.result())

    return "[Auto-Script Generation] Created the following files:\n" + "\n".join(results)


# -----------------------------------------------------------------
# Main loop - auto-research + auto-script generation + brain turns
# -----------------------------------------------------------------
def main():
    print("=" * 80)
    print(" JARVIS - Autonomous Multi-Tool Research + Auto-Script Generation")
    print(" Model: " + MODEL_NAME)
    print(" Type 'quit' or 'exit' to exit.")
    print("=" * 80)

    def emit(kind, payload):
        if kind == "tool":
            print(f"  [tool] {payload}")
        elif kind == "status" and payload == "escalating":
            print("  [escalating to cloud core...]")

    engine = BrainEngine(CFG, emit=emit)

    while True:
        try:
            user_input = input("\nYou: ").strip()
        except (KeyboardInterrupt, EOFError):
            print("\nJARVIS: Session ended.")
            break
        if not user_input:
            continue
        if user_input.lower() in ("quit", "exit"):
            print("\nJARVIS: Shutting down. Goodbye!")
            break
        if user_input.lower() == "reset":
            engine.reset()
            print("  [conversation cleared]")
            continue

        # ----- Automatic Research (legacy text-mode behaviour) -----
        if CFG.get("text_mode", {}).get("auto_research", True):
            auto_res = auto_research(user_input)
            if auto_res:
                engine.history.append({"role": "system", "content": auto_res})
                print(f"\n[Auto-Research injected]\n{auto_res[:200]}...\n")

        # ----- Automatic Script Generation -----
        script_summary = auto_generate_and_write_scripts(user_input)
        if script_summary:
            engine.history.append({"role": "system", "content": script_summary})
            print(f"\n{script_summary}\n")

        reply = engine.respond(user_input)
        if reply.error and reply.error != "busy":
            print(f"\n[!] {reply.error}")
        if reply.reply:
            print(f"\nJARVIS: {reply.reply}")


if __name__ == "__main__":
    main()
